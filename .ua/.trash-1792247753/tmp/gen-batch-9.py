def kind_of(fn, cls):
    n = fn["name"]
    if n.startswith("With"):
        return "setter"
    if n.startswith("ensure"):
        return "ensure"
    if n.startswith("Extract") or n.startswith("extract"):
        return "extract"
    if n.startswith("Get") or n.startswith("Is"):
        return "accessor"
    return "constructor"

def field_of(n):
    return n[4:] if n.startswith("With") else n

def fn_summary(fn, k, cls, typ):
    n = fn["name"]
    if k == "setter":
        return "Sets the %s field on %s and returns the receiver to support fluent chaining." % (field_of(n), cls)
    if k == "ensure":
        return "Lazily allocates the nested apply configuration required before %s setters can mutate it." % typ
    if k == "extract":
        if n == "Extract" + typ:
            return "Extracts the typed %s from an unstructured object so callers can read or modify it." % typ
        if n == "Extract" + typ + "Status":
            return "Extracts the %s status subresource from an unstructured object." % typ
        return "Internal helper that converts an unstructured object into a typed %s apply configuration." % typ
    if k == "accessor":
        if n.startswith("Is"):
            return "Reports whether the receiver is a valid apply configuration."
        return "Returns the %s value currently stored on the %s apply configuration." % (n[3:], typ)
    return "Constructs an empty %s builder for declaratively applying %s resources." % (cls, typ)

def fn_tags(k, typ):
    base = ["apply-configuration", "acme"]
    if k == "setter":
        return base + ["setter", "builder"]
    if k == "ensure":
        return base + ["builder", "initialization"]
    if k == "extract":
        return base + ["extraction", "conversion"]
    if k == "accessor":
        return base + ["accessor", "type-definition"]
    return base + ["constructor", "factory"]

nodes, edges = [], []
file_nodes = {}

for r in res["results"]:
    path = r["path"]
    base = path.split("/")[-1]
    typ, summary, tags = SPECS[base]
    lines = r["nonEmptyLines"]
    complexity = "simple" if lines < 50 else ("moderate" if lines <= 200 else "complex")
    fid = "file:" + path
    nodes.append({
        "id": fid, "type": "file", "name": base, "filePath": path,
        "summary": summary, "tags": tags, "complexity": complexity,
        "languageNotes": "Generated apply-configuration builder for the acme/v1 API group; all With* setters return the receiver for fluent chaining."
    })
    file_nodes[path] = fid

    for c in r.get("classes", []):
        cid = "class:%s:%s" % (path, c["name"])
        nodes.append({
            "id": cid, "type": "class", "name": c["name"], "filePath": path,
            "lineRange": [c["startLine"], c["endLine"]],
            "summary": "Apply configuration struct for %s, exposing fluent setters for its %s fields." % (typ, ", ".join(c.get("properties", [])) or "schema"),
            "tags": ["apply-configuration", "acme", "data-model", "builder"],
            "complexity": "moderate" if len(c.get("methods", [])) >= 5 else "simple"
        })
        edges.append({"source": fid, "target": cid, "type": "contains", "direction": "forward", "weight": 1.0})
        edges.append({"source": fid, "target": cid, "type": "exports", "direction": "forward", "weight": 0.8})

    for f in r.get("functions", []):
        k = kind_of(f, typ)
        fnode = {
            "id": "function:%s:%s" % (path, f["name"]), "type": "function", "name": f["name"], "filePath": path,
            "lineRange": [f["startLine"], f["endLine"]],
            "summary": fn_summary(f, k, typ + "ApplyConfiguration", typ),
            "tags": fn_tags(k, typ),
            "complexity": "simple"
        }
        nodes.append(fnode)
        edges.append({"source": fid, "target": fnode["id"], "type": "contains", "direction": "forward", "weight": 1.0})
        edges.append({"source": fid, "target": fnode["id"], "type": "exports", "direction": "forward", "weight": 0.8})

    for target in imports.get(path, []):
        edges.append({"source": fid, "target": "file:" + target, "type": "imports", "direction": "forward", "weight": 0.7})

# ---- partition ----
